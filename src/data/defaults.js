export function getCategoryMeta(catId) {
  return GARMENT_CATEGORIES.find((c) => c.id === catId) || GARMENT_CATEGORIES[0];
}

export function getDefaultConfigForCategory(catId) {
  const cat = getCategoryMeta(catId);
  if (cat.group === 'top_collar') {
    const isJacket = catId === 'jacket' || catId === 'outerwear';
    return {
      panjangPakaian: 0,
      panjangLengan: 'panjang',
      kerah: isJacket ? 'camp' : 'classic',
      modelBawah: 'straight',
      fitting: isJacket ? 'oversized' : 'regular',
      detail: isJacket ? ['saku', 'plaket'] : ['plaket'],
      primaryColor: isJacket ? '#5D87B8' : '#FFFFFF',
      twoTone: false,
      secondaryColor: '#4357FF',
      twoTonePattern: 'sleeves_collar'
    };
  }
  if (cat.group === 'top_knit') {
    return {
      panjangPakaian: 0,
      panjangLengan: catId === 'blouse' ? '3/4' : 'pendek',
      kerah: catId === 'blouse' ? 'sabrini' : 'crew',
      modelBawah: 'straight',
      fitting: 'regular',
      detail: [],
      primaryColor: catId === 'blouse' ? '#B9A2FF' : '#FFFFFF',
      twoTone: false,
      secondaryColor: '#FF4FA3',
      twoTonePattern: 'sleeves_collar'
    };
  }
  if (cat.group === 'bottom_pants') {
    return {
      panjangBawahan: 'full',
      pinggang: 'mid_rise',
      potonganKaki: 'straight',
      fittingBawahan: 'regular',
      detailBawahan: [],
      primaryColor: catId === 'jeans' ? '#5D87B8' : '#C8A27C',
      twoTone: false,
      secondaryColor: '#FF8A35',
      twoTonePattern: 'left_right'
    };
  }
  if (cat.group === 'bottom_skirt') {
    return {
      panjangBawahan: 'midi',
      pinggang: 'mid_rise',
      potonganKaki: 'pencil',
      fittingBawahan: 'regular',
      detailBawahan: [],
      primaryColor: '#5D87B8',
      twoTone: false,
      secondaryColor: '#FFE45E',
      twoTonePattern: 'left_right'
    };
  }
  return {
    panjangBawahan: 'midi',
    panjangLengan: 'pendek',
    kerah: 'crew',
    modelBawah: 'aline',
    fitting: 'regular',
    detail: [],
    primaryColor: '#FFE45E',
    twoTone: false,
    secondaryColor: '#FF4FA3',
    twoTonePattern: 'yoke_block'
  };
}

